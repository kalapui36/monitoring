  it('선택 학급으로 ZIP 생성을 요청하고 설치와 등록이 별도임을 안내한다', async () => {
    const download = vi.spyOn(studentPackage, 'downloadStudentPackage').mockImplementation(() => {})
    const user = userEvent.setup()
    render(<App />)
    await user.selectOptions(screen.getByRole('combobox', { name: '학급 선택' }), 'club-1')
    await user.click(screen.getByRole('button', { name: '학생 설치 안내' }))
    expect(screen.getByRole('dialog')).toHaveTextContent(
      '설치만으로 교사 화면에 학생이 등록되지는 않습니다.',
    )
    expect(screen.getByRole('dialog')).toHaveTextContent(
      '운영 중인 기존 확장을 삭제하거나 교체하지 마세요.',
    )
    await user.click(screen.getByRole('button', { name: '개발용 ZIP 다운로드' }))
    expect(download).toHaveBeenCalledWith(
      expect.objectContaining({ id: 'club-1', name: '코딩 동아리' }),
    )
  })
